-- ============================================================================
-- Assets register: what the organization owns (furniture, computers,
-- vehicles, machinery), who owns each item and what it cost. Run once, BEFORE
-- deploying the server code that mounts /api/assets. There is no migration
-- runner. Adds tables and one permission column; no existing row changes
-- except user_permissions.perm_assets. Not safe to re-run (CREATE TABLE
-- without IF NOT EXISTS and ALTER TABLE are intended: a second run stops at
-- the first statement).
--
-- 1. asset_types, asset_owners: managed lists. Names are stored cleaned
--    (trimmed, inner spaces collapsed) and are unique case-insensitively (the
--    server checks the normKey rule; the unique key under the table's _ci
--    collation also stops two parallel adds).
-- 2. assets: one row per entry. code (AST-0001) is generated by the server
--    from asset_code_counter inside the insert transaction, never reused and
--    never changed. total_price is what was paid (authoritative); unit_price
--    is a display value. A partial disposal splits the row: the disposed part
--    becomes a new row with its own code and split_from_id = the original.
--    updated_at / updated_by let an edit made against an older version be
--    refused (409 ASSET_CHANGED) and say who saved in between.
-- 3. asset_code_counter: one row holding the last number issued.
-- 4. user_permissions.perm_assets: everyone who has Finance today gets Assets.
-- Assets never post to Finance or any ledger.
-- ============================================================================

CREATE TABLE `asset_types` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(40) NOT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_asset_types_name` (`name`)
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE `asset_owners` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(60) NOT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_asset_owners_name` (`name`)
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE `assets` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `code` VARCHAR(12) NOT NULL,
  `name` VARCHAR(120) NOT NULL,
  `serial_no` VARCHAR(60) NULL DEFAULT NULL,
  `asset_type_id` INT NOT NULL,
  `owner_id` INT NOT NULL,
  `qty` INT NOT NULL,
  `unit_price` DECIMAL(14,2) NOT NULL,
  `total_price` DECIMAL(14,2) NOT NULL,
  `purchase_date` DATE NULL DEFAULT NULL,
  `description` VARCHAR(500) NULL DEFAULT NULL,
  `status` ENUM('in_use','disposed') NOT NULL DEFAULT 'in_use',
  `disposed_on` DATE NULL DEFAULT NULL,
  `disposal_note` VARCHAR(200) NULL DEFAULT NULL,
  `split_from_id` INT NULL DEFAULT NULL,
  `created_by` INT NULL DEFAULT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_by` INT NULL DEFAULT NULL,
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_assets_code` (`code`),
  KEY `idx_assets_type` (`asset_type_id`),
  KEY `idx_assets_owner` (`owner_id`),
  KEY `idx_assets_split_from` (`split_from_id`),
  CONSTRAINT `fk_assets_type` FOREIGN KEY (`asset_type_id`) REFERENCES `asset_types` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_assets_owner` FOREIGN KEY (`owner_id`) REFERENCES `asset_owners` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_assets_split_from` FOREIGN KEY (`split_from_id`) REFERENCES `assets` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_assets_created_by` FOREIGN KEY (`created_by`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_assets_updated_by` FOREIGN KEY (`updated_by`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `chk_assets_qty` CHECK (`qty` BETWEEN 1 AND 99999),
  CONSTRAINT `chk_assets_prices` CHECK (`unit_price` >= 0 AND `total_price` >= 0),
  CONSTRAINT `chk_assets_disposal` CHECK ((`status` = 'disposed') = (`disposed_on` IS NOT NULL))
) ENGINE = InnoDB DEFAULT CHARACTER SET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE `asset_code_counter` (
  `id` TINYINT NOT NULL,
  `last_no` INT NOT NULL,
  PRIMARY KEY (`id`)
) ENGINE = InnoDB;
INSERT INTO `asset_code_counter` (`id`, `last_no`) VALUES (1, 0);

ALTER TABLE `user_permissions`
  ADD COLUMN `perm_assets` TINYINT(1) NOT NULL DEFAULT 0 AFTER `perm_finance`;
UPDATE `user_permissions` SET `perm_assets` = `perm_finance`;

-- ── Review: users who now have Assets (expect exactly the Finance users) ──
SELECT u.id, u.username, u.full_name, up.perm_finance, up.perm_assets
  FROM users u JOIN user_permissions up ON up.user_id = u.id
 WHERE up.perm_assets <> up.perm_finance OR up.perm_assets = 1;
